// Builds qa/evidence.json from three inputs and nothing else:
//   qa/seed-facts.json   immutable, written verbatim from the brief
//   content/**.json      the data the site actually renders
//   qa/claims-manual.json prose assertions hardcoded in src/ rather than driven from content
// It never invents a source. A claim it cannot anchor comes out UNVERIFIED.
import fs from "node:fs";
import path from "node:path";

const seed = JSON.parse(fs.readFileSync("qa/seed-facts.json", "utf8"));
const manual = JSON.parse(fs.readFileSync("qa/claims-manual.json", "utf8"));

function walk(dir, out = []) {
  for (const n of fs.readdirSync(dir)) {
    const p = path.join(dir, n);
    fs.statSync(p).isDirectory() ? walk(p, out) : p.endsWith(".json") && out.push(p);
  }
  return out;
}

// Claim types worth a row. A section label is not a claim; a bank account is.
const HIGH_COST = /^(orgNumber|bank|vipps|phone|email|priceNok|durationHours|capacity|nextDateIso|memberCount|membershipFeeNok|foundedIso|registeredIso|bylawsAmendedIso|publishedAt|eventStartsAt|eventEndsAt|year|nok|regulator|asOfIso|amendedIso|leadImage|href)$/;

const rows = [];
for (const file of walk("content")) {
  const doc = JSON.parse(fs.readFileSync(file, "utf8"));
  const visit = (node, pointer) => {
    if (node === null || typeof node !== "object") {
      const key = pointer.split("/").pop();
      if (!HIGH_COST.test(key)) return;
      rows.push({
        claim: node === null ? "(null, must render as a stated absence)" : String(node),
        renderedOn: [],
        source: "content",
        file,
        pointer,
        literal: node === null ? null : String(node),
      });
      return;
    }
    if (Array.isArray(node)) return node.forEach((v, i) => visit(v, `${pointer}/${i}`));
    Object.entries(node).forEach(([k, v]) => visit(v, `${pointer}/${k}`));
  };
  visit(doc, "");
}

for (const f of seed.facts) {
  rows.push({
    claim: f.value === null ? "(null, must render as a stated absence)" : String(f.value),
    renderedOn: [],
    source: "brief",
    file: "qa/seed-facts.json",
    pointer: f.id,
    literal: f.value === null ? null : String(f.value),
  });
}

rows.push(...manual.rows);

const out = {
  _: "Generated by qa/build-evidence.mjs. Verified by qa/gates/evidence-anchor.mjs (gate G22).",
  generatedFrom: ["qa/seed-facts.json", "content/**/*.json", "qa/claims-manual.json"],
  rows,
};
fs.writeFileSync("qa/evidence.json", JSON.stringify(out, null, 2) + "\n");

const bySource = rows.reduce((a, r) => ((a[r.source] = (a[r.source] || 0) + 1), a), {});
console.log("evidence.json rows:", rows.length, bySource);
